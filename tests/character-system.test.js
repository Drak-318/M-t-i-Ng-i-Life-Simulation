const assert = require("node:assert/strict");
global.window = global;
require("../src/character-system.js");
const CS = global.CharacterSystem;
assert.ok(CS, "CharacterSystem must load");
const linh = CS.createLinh();
const npc = CS.createBackgroundCharacter(4);
assert.equal(linh.age, 24);
assert.ok(linh.schedule["1"].length >= 2);
assert.ok(npc.age >= 18);
assert.ok(npc.personality && npc.needs && npc.boundaries && npc.communication);
assert.ok(npc.appearance && npc.appearance.top.length === 3);
const before = linh.energy;
CS.tick(linh, 60, 2, 10);
assert.ok(linh.energy < before, "work schedule should consume energy");
assert.equal(CS.scheduleEntry(linh, 2, 19).location, "home");
const scene = CS.interaction(linh, {stress: 20});
assert.ok(scene.choices.length >= 3);
CS.applyRelationship(linh, {trust: 3, m: "test_memory"}, 2, 600);
assert.equal(linh.relationship.trust, 3);
assert.ok(CS.hasMemory(linh, "test_memory"));
const saved = CS.serialize([linh,npc]);
linh.energy = 1;
CS.restore([linh,npc], saved);
assert.notEqual(linh.energy, 1);
console.log("Character System tests: PASS");
